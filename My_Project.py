#what is flask?
#Flask is a micro web framework written in Python. It is designed to be lightweight and easy to use, making it a popular choice for building web applications. Flask provides a simple and flexible way to create web applications, allowing developers to focus on writing their application logic rather than dealing with the complexities of web development. It includes features such as routing, templating, and support for various extensions that can be used to add functionality to your application. Flask is often used for building small to medium-sized web applications, APIs, and prototypes.


